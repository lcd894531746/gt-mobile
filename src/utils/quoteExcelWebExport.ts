  sheet.getCell(totalRow, 1).value = '\u5408\u8ba1\uff08\u5927\u5199\uff09\uff1a';
  const words = String(pickValue(payload, ['totalAmountInWords', '\u91d1\u989d\u5927\u5199'], '')).trim();
  sheet.getCell(totalRow, 3).value = words && !/^\d+(\.\d+)?$/.test(words) ? words : amountToChineseUpper(totalAmount);
  sheet.getCell(totalRow, 7).value =
    '\u5c0f\u5199\uff1a \uffe5' +
    totalAmount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

  for (let col = 1; col <= visibleColumnCount; col += 1) {
    const cell = sheet.getCell(totalRow, col);
    cell.border = border;
    cell.fill = greenFill;
    cell.font = { name: 'SimHei', size: 10, bold: true };
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
  }

  for (const rowIndex of [totalRow + 1, totalRow + 2]) {
    for (let col = 1; col <= visibleColumnCount; col += 1) {
      const cell = sheet.getCell(rowIndex, col);
      cell.fill = greenFill;
      cell.border = gridBorder;
      cell.font = { name: 'SimHei', size: 10 };
      cell.alignment = { horizontal: 'left', vertical: 'middle' };
    }
  }

  sheet.mergeCells(totalRow + 1, 1, totalRow + 1, 3);
  sheet.getCell(totalRow + 1, 1).value = '\u4ea7\u54c1\u62a5\u4ef7\uff0c\u8bf7\u6ce8\u610f\u4fdd\u5bc6\u3002';

  sheet.mergeCells(totalRow + 2, 7, totalRow + 2, 9);
  const dateParts = formatDate(pickValue(payload, ['orderDate', '\u65e5\u671f'])).split('-');
  const exportDate =
    dateParts.length === 3
      ? `${dateParts[0]}\u5e74${dateParts[1]}\u6708${dateParts[2]}\u65e5`
      : dateParts.join('');
  sheet.getCell(totalRow + 2, 7).value = '\u65e5\u671f\uff1a' + exportDate;
  sheet.getCell(totalRow + 2, 7).alignment = { horizontal: 'center', vertical: 'middle' };

  sheet.pageSetup.printArea = `A1:I${lastContentRow}`;

  for (let row = lastContentRow + 1; row <= maxRowCount; row += 1) {
    sheet.getRow(row).hidden = true;
  }

  const buffer = await workbook.xlsx.writeBuffer();
  downloadBuffer(buffer as ArrayBuffer, fileName);
